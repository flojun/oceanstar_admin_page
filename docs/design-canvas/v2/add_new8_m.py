    d = json.load(io.open(p, encoding="utf-8"))
    d["artboards"] = [a for a in d["artboards"] if a["file"] != "New8_M.dc.html"]
    d["annotations"] = [a for a in d["annotations"] if a["id"] != "new8-m"]

