# -*- coding: utf-8 -*-
"""새-8 을 캔버스 3열 오른쪽에 붙인다."""
import io
import json

NOTE = """새-8 · 스크롤 투어

새-6 의 배치를 뼈대로 쓰되, 조판이 아니라 투어 UI 로 다시 짜고 스크롤 연출을 전제로 설계했습니다.

배치는 새-6 그대로입니다
히어로 영상 → 소개 띠 → 지표 → 투어 고르기 → 상품 상세(사진↔활자 교차) → 예약 유도 띠

에디토리얼에서 투어로 바꾼 것
· 헤어라인 표를 썸네일·요금·화살표가 붙은 '고르는 줄'로 바꿨습니다. 표는 읽는 물건이고 이건 누르는 물건입니다.
· 사진을 둥근 액자에 넣고 뒤로 하늘색 판을 어긋나게 깔아 깊이를 만들었습니다.
· 스펙은 옅은 판 세 칸, 포함 사항은 체크 목록, 값 옆엔 꽉 찬 예약 버튼.
· 색이 잉크 흑백에서 브랜드 파랑으로 돌아왔습니다. 액티비티 투어의 온도에 맞췄습니다.

스크롤 연출은 그림만이 아니라 지금 CSS 로 들어가 있습니다
animation-timeline: view() 를 써서 스크립트 없이 동작합니다.
· 섹션 머리·지표·고르는 줄 — 아래에서 떠오릅니다. 순서는 진입 구간을 조금씩 밀어 만듭니다.
· 상세 행 — 사진은 작게 부풀며 들어오고, 활자는 사진 반대편에서 미끄러져 들어옵니다.
· 사진은 액자 안에서 통과하는 내내 천천히 물러나 시차가 생깁니다.
· 히어로 활자는 스크롤과 함께 떠오르며 비켜줍니다.

설계상 지킨 규칙은 하나입니다. 쉬는 상태가 기본값이고 키프레임은 '숨김 → 보임' 방향으로만 갑니다. 그래서 캔버스 뷰어·PDF·모션 최소화 설정에서는 그냥 다 보이는 화면이 됩니다. 반대로 짜면 인쇄물이 백지가 됩니다.

캔버스와 PDF 는 정지 화면이라 움직임이 안 보입니다. 함께 드린 '새-8_스크롤확인.html' 을 브라우저로 열면 실제로 굴려볼 수 있습니다.

걸리는 점
페이지가 6,117px 로 가장 깁니다. 고르는 줄과 상세 행이 같은 내용을 두 번 보여주는 구조라, 고르는 줄을 빼면 눈에 띄게 줄어듭니다."""


def main():
    p = "canvas.json"
    d = json.load(io.open(p, encoding="utf-8"))
    d["artboards"] = [a for a in d["artboards"] if a["file"] != "New8.dc.html"]
    d["annotations"] = [a for a in d["annotations"]
                        if not a["text"].startswith("새-8")]
    d["artboards"].append({"file": "New8.dc.html",
                           "title": "새-8 · 스크롤 투어 — 데스크탑 1440",
                           "x": 3200, "y": 8100, "w": 1440, "h": 6200})
    d["annotations"].append({"x": 3200, "y": 7480, "w": 1440, "text": NOTE})
    json.dump(d, io.open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print("canvas ok:", len(d["artboards"]), "artboards")


if __name__ == "__main__":
    main()
