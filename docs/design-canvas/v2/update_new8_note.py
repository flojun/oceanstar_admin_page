"""새-8 아트보드 높이와 설명을 지금 상태에 맞춘다."""
import io
import json

H = 5450  # 실측 5363 + 여유

NOTE = """새-8 · 스크롤 투어

새-6 의 배치를 뼈대로 쓰되, 조판이 아니라 투어 UI 로 다시 짜고 스크롤 연출을 전제로 설계한 안입니다.

구성
히어로 영상 → 소개 띠 → 지표 → 오션스타 추천 프로그램(사진↔활자 교차) → 푸터

추천 프로그램
가로로 훑는 목록 대신 펼쳐 보는 방식 하나만 남겼습니다. 사진은 둥근 액자에 넣고 뒤로 하늘색 판을 어긋나게 깔았고, 오른쪽에 운영 시간 / 정원 / 요금 기준 세 칸과 포함 사항 체크 목록, 값 옆에 예약 버튼을 뒀습니다. 사진 위 번호는 뺐습니다.

표의 값은 지어낸 게 아니라 기존 상품 데이터에서 읽어온 것입니다. 없는 값은 빈칸으로 두지 않고 [운영 시간 확정 필요] 표기를 그대로 노출합니다.

푸터
운영 중인 사이트 맨 아래 내용을 그대로 옮겼습니다. 영업시간, 인스타·유튜브·맛집 리스트, 이메일과 주소, 사업자 정보, 저작권 줄까지 문구를 손대지 않았습니다. 본문이 흰 바탕으로 끝나므로 네이비로 받아 페이지를 닫습니다. 아이콘은 이모지가 아니라 선으로 그려 크기와 색을 따라옵니다.

스크롤 연출은 그림만이 아니라 지금 CSS 로 들어가 있습니다
animation-timeline: view() 를 써서 스크립트 없이 동작합니다.
· 섹션 머리 · 지표 · 푸터 — 아래에서 떠오릅니다. 순서는 진입 구간을 조금씩 밀어 만듭니다.
· 상품 행 — 사진은 작게 부풀며 들어오고, 활자는 사진 반대편에서 미끄러져 들어옵니다.
· 사진은 액자 안에서 통과하는 내내 천천히 물러나 시차가 생깁니다.
· 히어로 활자는 스크롤과 함께 떠오르며 비켜줍니다.

설계상 지킨 규칙은 하나입니다. 쉬는 상태가 기본값이고 키프레임은 '숨김 → 보임' 방향으로만 갑니다. 그래서 캔버스 뷰어·PDF·모션 최소화 설정에서는 그냥 다 보이는 화면이 됩니다. 반대로 짜면 인쇄물이 백지가 됩니다.

캔버스와 PDF 는 정지 화면이라 움직임이 안 보입니다. 함께 드린 '새-8_스크롤확인.html' 을 브라우저로 열면 실제로 굴려볼 수 있습니다."""


def main():
    p = "canvas.json"
    d = json.load(io.open(p, encoding="utf-8"))
    board = next(a for a in d["artboards"] if a["file"] == "New8.dc.html")
    board["h"] = H
    note = next(a for a in d["annotations"] if a["id"] == "new8-scroll")
    note["text"] = NOTE
    note["x"], note["w"] = board["x"], board["w"]
    json.dump(d, io.open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print("New8 h=%d, note %d자" % (board["h"], len(NOTE)))


if __name__ == "__main__":
    main()
